// Turns research/branch-locations.json into the BRANCHES block in
// src/data/restaurants.js, so every branch of a multi-branch place carries
// its own researched address, hours, phone and pin.
//
//   node scripts/apply-branches.mjs            # report only
//   node scripts/apply-branches.mjs --write    # write the BRANCHES block
//
// A branch Google did not resolve keeps only its name: the site then shows
// the area and a Maps search for it, and never invents the rest.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { restaurants } from "../src/data/restaurants.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCAN = path.join(ROOT, "research", "branch-locations.json");
const DATA_FILE = path.join(ROOT, "src", "data", "restaurants.js");
const MARK_START = "// >>> BRANCHES (generated by scripts/apply-branches.mjs)";
const MARK_END = "// <<< BRANCHES";

const args = process.argv.slice(2);
const write = args.includes("--write");

if (!fs.existsSync(SCAN)) {
  console.log("No research/branch-locations.json yet. Run scripts/research-branches.mjs first.");
  process.exit(1);
}
const scan = JSON.parse(fs.readFileSync(SCAN, "utf8"));
const found = scan.results || {};

let branches = 0;
let detailed = 0;
const lines = ["  "];
for (const restaurant of restaurants) {
  if (restaurant.branches.length < 2) continue;
  const entries = [];
  for (const name of restaurant.branches) {
    const record = found[`${restaurant.id}::${name}`];
    const entry = { name };
    if (record) {
      detailed += 1;
      // Google sometimes prefixes the address with the coordinates.
      const address = String(record.address || "").replace(/^\d{2}\.\d{3,},\s*\d{2}\.\d{3,},\s*/, "");
      if (address) entry.address = address;
      if (record.area) entry.area = record.area;
      if (record.phone) entry.phone = record.phone;
      if (record.hours && Object.keys(record.hours).length) entry.hours = record.hours;
      if (record.openNow) entry.openNow = record.openNow;
      if (record.lat && record.lng) {
        entry.lat = record.lat;
        entry.lng = record.lng;
      }
      if (record.placeId) entry.placeId = record.placeId;
    }
    entries.push(entry);
  }
  branches += entries.length;
  const body = entries
    .map((entry) => `      ${JSON.stringify(entry).replace(/","/g, '", "')}`)
    .join(",\n");
  lines.push(`  ${JSON.stringify(restaurant.id)}: {\n    locations: [\n${body}\n    ],\n  },\n`);
}

console.log(`branch records: ${branches} across ${lines.filter((l) => l.includes(": {")).length} places`);
console.log(`with researched detail: ${detailed}`);
console.log(`name only (Google did not resolve it): ${branches - detailed}`);

if (!write) {
  console.log(`\nNothing written. Re-run with --write to update ${path.relative(ROOT, DATA_FILE)}.`);
  process.exit(0);
}

const now = new Date().toISOString().slice(0, 10);
const block = `${MARK_START}\n// Every branch of a multi-branch place, researched on ${now}. A branch\n// Google did not resolve keeps only its name, so nothing is invented.\nconst BRANCHES = {\n${lines.join("\n")}};\n${MARK_END}`;

let source = fs.readFileSync(DATA_FILE, "utf8");
const start = source.indexOf(MARK_START);
const end = source.indexOf(MARK_END);
if (start >= 0 && end > start) {
  source = source.slice(0, start) + block + source.slice(end + MARK_END.length);
} else {
  const anchor = "let n = 0;";
  source = source.replace(anchor, `${block}\n\n${anchor}`);
}
// mk() applies the researched values last, branches after them.
source = source.replace(
  "    ...(RESEARCHED[id] || {}),\n  };\n}",
  "    ...(RESEARCHED[id] || {}),\n    ...(BRANCHES[id] || {}),\n  };\n}",
);
fs.writeFileSync(DATA_FILE, source);
console.log(`\nWrote ${path.relative(ROOT, DATA_FILE)}.`);
