// Turns research/maps-scan.json into a reviewable diff against the current data,
// and (with --write) regenerates the RESEARCHED block in src/data/restaurants.js.
//
//   node scripts/apply-research.mjs            # report only
//   node scripts/apply-research.mjs --write    # write the RESEARCHED block
//
// Safety rules:
//   * only records with a confident name match (--min-score, default 0.6) are used
//   * a place Google does not call food is never accepted
//   * cuisine only changes when Google's categories map cleanly; anything
//     ambiguous is listed under "needs a decision" and left alone
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { restaurants } from "../src/data/restaurants.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCAN = path.join(ROOT, "research", "maps-scan.json");
const DATA_FILE = path.join(ROOT, "src", "data", "restaurants.js");
const MARK_START = "// >>> RESEARCHED (generated by scripts/apply-research.mjs)";
const MARK_END = "// <<< RESEARCHED";

const args = process.argv.slice(2);
const write = args.includes("--write");
const minScore = Number((args.find((a) => a.startsWith("--min-score=")) || "--min-score=0.6").split("=")[1]);

// Google category -> the food types this directory can filter by.
// Kept in step with CUISINE_FIX in restaurants.js so the researched value and
// the hand-written value can never disagree about what a category means.
const CATEGORY_MAP = [
  [/(^|\b)pizza|pizzeria/i, "Pizza"],
  [/burger|hamburger/i, "Burger"],
  [/fried chicken|chicken (restaurant|shop|joint)|fried chicken/i, "Fried Chicken"],
  [/(^|\b)grill|barbecue|\bbbq\b|steakhouse|steak house|steak|meat restaurant|butcher|churrasco|persian|iranian|afghan|uzbek|kazakh|mongolian grill/i, "Grill"],
  [/pasta|trattoria|spaghetti|carbonara/i, "Pasta"],
  [/italian/i, "Italian"],
  [/indian|biryani|pakistani|bengali|curry|tandoori|punjabi|mughlai|thali|paratha|chaat|desi/i, "Indian"],
  [/chinese|asian|japanese|sushi|thai|korean|vietnamese|filipino|indonesian|malaysian|tibetan|nepalese|mongolian/i, "Asian"],
  [/lebanese|middle eastern|syrian|iraqi|palestinian|jordanian|egyptian|turkish|greek|cypriot|mediterranean|moroccan|berber|tunisian|falafel|shawarma|hookah|kebab/i, "Mediterranean"],
];
// Google categories that say nothing about what kind of food this is.
const IGNORED_CATEGORIES = /seafood|sea food|fish|bakery|dessert|ice cream|juice|smoothie|cafe|coffee|breakfast|brunch|fast food|sandwich|deli|market|supermarket|catering|buffet|food court|hotel|tea|takeaway|takeout|delivery|attraction|diner/i;
// Words in the place name itself are evidence too: Google leaves many places
// categorised as a bare "Restaurant".
const NAME_HINT = [
  [/broast|بروست/i, "Broasted"],
  [/pizza|pizzeria/i, "Pizza"],
  [/burger|hamburger/i, "Burger"],
  [/pasta|trattoria|spaghetti/i, "Pasta"],
  [/indian|curry|biryani|tandoori/i, "Indian"],
  [/chinese|sushi|thai|japanese|korean|asian|noodle/i, "Asian"],
  [/shawarma|falafel|kebab|lebanese|syrian|iraqi|palestinian|turkish|greek|egyptian|mediterranean/i, "Mediterranean"],
  [/grill|grills|bbq|barbecue|steak|churrasco|persian|kebab/i, "Grill"],
];

/**
 * What the site should show as the food type, and how sure we are.
 * "unmapped" simply means Google added no information, which is not a problem.
 */
function mapCuisine(categories, currentCuisine, googleName = "") {
  const found = [];
  const foodCategories = categories.filter((c) => !IGNORED_CATEGORIES.test(c));
  for (const category of foodCategories) {
    for (const [re, cuisine] of CATEGORY_MAP) {
      if (re.test(category) && !found.some((f) => f.cuisine === cuisine)) found.push({ cuisine, from: category, primary: category === foodCategories[0] });
    }
  }
  // The name can add evidence Google's category list leaves out.
  for (const [re, cuisine] of NAME_HINT) {
    if (re.test(googleName) && !found.some((f) => f.cuisine === cuisine)) {
      found.push({ cuisine, from: `name "${googleName}"`, primary: false });
    }
  }
  if (!found.length) return { cuisine: null, confidence: "unmapped" };
  if (found.some((f) => f.cuisine === currentCuisine)) return { cuisine: currentCuisine, confidence: "agree" };
  if (currentCuisine === "Broasted") {
    // Broasted is the narrower Arabic-style chicken type; never overwrite it.
    return { cuisine: currentCuisine, confidence: "keep-broasted" };
  }
  if (found.length > 1) return { cuisine: found[0].cuisine, confidence: "ambiguous" };
  return { cuisine: found[0].cuisine, confidence: found[0].primary ? "high" : "medium" };
}

// Areas we trust as a Location filter value.
const KNOWN_AREAS = [
  "Manama", "Adliya", "Amwaj", "Gudaif", "Juffair", "Seef", "Al Seef", "A'ali", "Aali", "Jidar Al Aali",
  "Busaiteen", "Riffa", "Riffa Views", "Sitra", "Sahlat", "Al Saya", "Karbabad", "Janabiyah",
  "Al Budaiya", "Budaiya", "Saar", "Al Qalali", "Qalali", "Tubarat", "Tubli", "Muharraq", "Hidd",
  "Halat Al Sahlat", "Abu Rayyan", "Ain Ashi", "Diyar Al Muharraq", "Hamad Town", "Isa Town",
  "Awl", "Kalaif", "Karranah", "Malkiya", "Awala", "Um Al Hassam", "Arad", "Askar", "Zinjawar",
  "Samir", "Baharna", "Awali", "Durrat Al Bahrain", "Dar Zoom", "Al Areen", "Valley City",
  "Sadeen", "Al Jurf", "Al Sayh", "Sanad", "Bilad Al Qadeem", "Maqabah", "Jurdab", "Jerdab",
  "Diyar", "Al Qalaliyah", "Mahooz", "Al Hoor", "Al Faha", "Reef", "Faha", "Barbar",
];
const knownArea = (value) => KNOWN_AREAS.find((a) => new RegExp(`\\b${a.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\b`, "i").test(String(value || "")));

/** Google mixes in a plus code, an Arabic-only street name and a repeated area. */
function tidyAddress(value) {
  let out = String(value || "")
    // a leading plus code: "4HHQ+9V6, Rd No 4616, Nuwaidrat, Riffa"
    .replace(/^[0-9A-Z]{4,}\+[0-9A-Z]{2,},?\s*/i, "")
    // a leading Arabic-only segment: "مدينة الشواء, Bilad Al Qadeem"
    .replace(/^[\u0600-\u06FF\u0750-\u077F\uFB50-\uFDFF\uFE70-\uFEFF\s]+,/, "")
    // a direction letter glued to a building number: "Building 605د"
    .replace(/(\d)[\u0600-\u06FF\u0750-\u077F]+/g, "$1")
    .replace(/\s*،\s*/g, ", ")
    .replace(/[،؛]/g, ",")
    .replace(/\s{2,}/g, " ")
    .replace(/,\s*,/g, ",");

  // A plus code hides in two places: on its own as a whole segment
  // ("1334, Maqabah"), or dangling off the end of one ("Al Seef 0428, Seef",
  // "Hamad Town 1038"). Labelled numbers (Road 3803, Building 2214) are real
  // and must survive.
  const LABEL = /\b(building|shop|block|road|rd|no|unit|flat|bldg)\b/i;
  const areaAlternatives = KNOWN_AREAS.map((a) => a.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
  const isArea = (value) => new RegExp(`^(${areaAlternatives})$`, "i").test(String(value || "").trim());
  const parts = out.split(",").map((part) => part.trim()).filter(Boolean);
  const kept = [];
  for (let i = 0; i < parts.length; i += 1) {
    const part = parts[i];
    if (/^\+?\d{3,4}$/.test(part)) continue; // a segment that is only digits
    const dangling = part.match(/^(.*\S)\s(\d{3,4})$/);
    const isLast = i === parts.length - 1;
    if (dangling && !LABEL.test(dangling[1]) && (isLast || isArea(parts[i + 1]))) {
      kept.push(dangling[1]);
      continue;
    }
    kept.push(part);
  }
  out = kept.join(", ");
  // "Al Seef, Seef" keeps one copy; any word repeated back to back goes too.
  out = out.replace(new RegExp(`\\b(?:al\\s+)?(${areaAlternatives})\\b,\\s*(?:al\\s+)?\\1\\b`, "gi"), "$1");
  out = out.replace(/\b(\w{3,})\s+\1\b/gi, "$1");
  return out.replace(/,\s*$/, "").replace(/\s{2,}/g, " ").trim();
}

/**
 * The panel scraper can hand back a gstatic icon path or the category list where
 * an address should be. Anything that is not an address is rejected here.
 */
const NOT_AN_ADDRESS = /^(https?:|data:)|gstatic|googleapis|googleusercontent|\.(png|jpe?g|webp|svg|gif)$/i;
function usableAddress(value, categories = []) {
  const text = String(value || "").trim();
  if (!text) return "";
  if (NOT_AN_ADDRESS.test(text)) return "";
  const parts = text.split(",").map((part) => part.trim().toLowerCase());
  const known = new Set(categories.map((c) => c.toLowerCase()));
  if (parts.length > 1 && parts.every((part) => known.has(part))) return ""; // it is the category list
  if (known.has(text.toLowerCase())) return "";
  return text;
}

/**
 * The short form of an address for the card:
 * "Sea side, Block 346, Avenues, store N:2, Manama" -> "Avenues, Manama".
 * The full Google address stays behind the Maps link.
 */
const ADDRESS_NOISE = /^(block|building|road|rd|road no|shop|store|unit|level|flat|area|sea ?side|district|near|opposite|behind|beside|entrance|phase)/i;
function tidyShort(value) {  const parts = String(value || "")
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean)
    .filter((part) => !ADDRESS_NOISE.test(part))
    .filter((part) => !/^[+0-9A-Z]{4,}$/.test(part) && !/^\d+$/.test(part));
  return parts.slice(0, 2).join(", ");
}

/** A bare plus code says less than the area name we already have. */
function isUsefulAddress(value) {  const words = String(value || "").replace(/[0-9٠-٩]+/g, " ").split(/[^A-Za-z\u0600-\u06FF]+/).filter(Boolean);
  return words.length >= 2;
}

const scan = JSON.parse(fs.readFileSync(SCAN, "utf8"));
const byId = new Map(scan.results.map((r) => [r.id, r]));
const now = new Date().toISOString().slice(0, 10);

const accepted = [];
const rejected = [];
const decisions = [];
const fieldChanges = [];

for (const restaurant of restaurants) {
  const record = byId.get(restaurant.id);
  if (!record?.resolved) {
    rejected.push({ id: restaurant.id, name: restaurant.name, why: record?.error || "not researched" });
    continue;
  }
  const r = record.resolved;
  if ((record.nameScore ?? 0) < minScore) {
    rejected.push({ id: restaurant.id, name: restaurant.name, found: r.name, why: `name match ${record.nameScore}` });
    continue;
  }
  accepted.push({ id: restaurant.id, name: restaurant.name, found: r.name, score: record.nameScore });

  const patch = {};
  const changes = [];

  // Location: keep Google's street address when it says more than what we have,
  // and a clean area name for the Location filter.
  const googleAddress = tidyAddress(usableAddress(r.address, r.categories));
  const googleArea = r.area || knownArea(googleAddress) || "";
  const currentIsArea = knownArea(restaurant.address);
  if (googleAddress && googleAddress !== restaurant.address && isUsefulAddress(googleAddress)) {
    const sameInfo = googleAddress.replace(/[^a-z]/gi, "").toLowerCase() === restaurant.address.replace(/[^a-z]/gi, "").toLowerCase();
    const moreDetail = googleAddress.length > restaurant.address.length + 3;
    const currentIsBareArea = !currentIsArea;
    if (!sameInfo && (moreDetail || currentIsBareArea)) {
      patch.address = googleAddress;
      patch.shortAddress = tidyShort(googleAddress);
      changes.push(`address: "${restaurant.address}" -> "${googleAddress}"`);
    }
  } else if (restaurant.address) {
    // Carry our own wording forward, but never a value the scraper mangled:
    // if it is not an address, leave the field out so the curated one in the
    // mk() call shows through.
    if (usableAddress(restaurant.address, r.categories)) {
      patch.address = restaurant.address;
      patch.shortAddress = tidyShort(restaurant.address);
    }
  }
  // Keep our own area whenever it is already a real area name: "Seef" beats a
  // Google string that only reaches the governorate ("Bu Ghazal Manama").
  if (googleArea && !currentIsArea && !restaurant.area) {
    patch.area = googleArea;
    changes.push(`area: "${restaurant.address}" -> ${googleArea}`);
  } else if (restaurant.area) {
    patch.area = restaurant.area;
  }
  // Phone: fill a gap, never drop a branch number we already had.
  const googlePhone = (r.phone || "").replace(/\s*\/.*$/, "");
  if (googlePhone) {
    if (!restaurant.phone) {
      patch.phone = googlePhone;
      changes.push(`phone: "-" -> ${googlePhone}`);
    } else if (!restaurant.phone.includes(googlePhone.replace("+973 ", ""))) {
      patch.phone = `${restaurant.phone} / ${googlePhone}`;
      changes.push(`phone: added Google number -> ${patch.phone}`);
    } else {
      // already researched on an earlier run: carry it so the block is stable
      patch.phone = restaurant.phone;
    }
  }
  // The researched value always wins, and is always written, so re-running this
  // script cannot quietly drop what a previous run put there.
  if (r.rating) {
    patch.rating = r.rating;
    patch.reviews = r.reviews;
    if (r.rating !== restaurant.rating) {
      changes.push(`rating: ${restaurant.rating ?? "-"}/${restaurant.reviews ?? "-"} -> ${r.rating}/${r.reviews ?? "-"} (Google)`);
    }
  } else if (restaurant.rating) {
    patch.rating = restaurant.rating;
    patch.reviews = restaurant.reviews;
    changes.push("rating: Google lists no rating; keeping the researched value");
  } else {
    changes.push("rating: Google lists no rating for this place");
  }
  if (r.website && !/instagram\.com/i.test(r.website)) patch.website = r.website.startsWith("http") ? r.website : `https://${r.website}`;
  if (r.placeId) patch.mapsPlaceId = r.placeId;
  // A single published day is only trustworthy when it says "Open 24 hours".
  const hourValues = Object.values(r.hours || {}).filter(Boolean);
  if (hourValues.length >= 2 || (hourValues.length === 1 && /24\s*hours/i.test(hourValues[0]))) {
    patch.openingHours = r.hours;
  }
  if (r.lat && r.lng) { patch.lat = r.lat; patch.lng = r.lng; }
  if (r.categories.length) patch.categories = r.categories;
  if (r.nameAr) patch.nameAr = r.nameAr;
  if (r.openNow) patch.openNow = r.openNow;
  patch.dataSource = "google-maps";
  patch.googleName = r.name;

  const mapped = mapCuisine(r.categories, restaurant.cuisine, r.name);
  if (mapped.confidence === "high" && mapped.cuisine !== restaurant.cuisine) {
    patch.cuisine = mapped.cuisine;
    changes.unshift(`CUISINE: ${restaurant.cuisine} -> ${mapped.cuisine} (${r.categories.join(", ")})`);
  } else if (mapped.confidence === "medium" || mapped.confidence === "ambiguous") {
    decisions.push({
      id: restaurant.id,
      name: restaurant.name,
      question: `Google says ${mapped.cuisine} ("${r.name}"), we say ${restaurant.cuisine}`,
      categories: r.categories,
    });
  }
  if (patch.cuisine === undefined) patch.cuisine = restaurant.cuisine;

  if (changes.length) fieldChanges.push({ id: restaurant.id, name: restaurant.name, changes });
  if (Object.keys(patch).length > 2) accepted[accepted.length - 1].patch = patch;
  if (patch) (byId.get(restaurant.id).patch = patch);
}

console.log(`\n=== RESEARCH DIFF (${now}) ===`);
console.log(`scanned ${scan.results.length} | accepted ${accepted.length} | needs review ${decisions.length} | unresolved ${rejected.length}`);

console.log(`\n--- field changes (${fieldChanges.length}) ---`);
for (const c of fieldChanges) console.log(`  ${c.id} (${c.name})\n      ${c.changes.join("\n      ")}`);

console.log(`\n--- cuisine changes to apply automatically ---`);
for (const c of fieldChanges.filter((c) => c.changes.some((x) => x.startsWith("CUISINE")))) {
  console.log(`  ${c.id}: ${c.changes.find((x) => x.startsWith("CUISINE"))}`);
}

console.log(`\n--- needs a decision (${decisions.length}) ---`);
for (const d of decisions) console.log(`  ${d.id} (${d.name}): ${d.question}`);

console.log(`\n--- rejected / not resolved (${rejected.length}) ---`);
for (const r of rejected) console.log(`  ${r.id} (${r.name}): ${r.why}${r.found ? ` -> found "${r.found}"` : ""}`);

if (!write) {
  console.log(`\nNothing written. Re-run with --write to update ${path.relative(ROOT, DATA_FILE)}.`);
  process.exit(0);
}

// --- write the RESEARCHED block -------------------------------------------
const lines = ["  "];
for (const restaurant of restaurants) {
  const patch = byId.get(restaurant.id)?.patch;
  if (!patch) continue;
  const order = ["googleName", "nameAr", "cuisine", "address", "shortAddress", "area", "phone", "rating", "reviews", "website", "categories", "openNow", "openingHours", "mapsPlaceId", "lat", "lng", "dataSource"];
  const body = order
    .filter((key) => patch[key] !== undefined)
    .map((key) => `    ${key}: ${JSON.stringify(patch[key])},`)
    .join("\n");
  lines.push(`  ${JSON.stringify(restaurant.id)}: {\n${body}\n  },\n`);
}
const block = `${MARK_START}\n// Google Maps values researched on ${now}. This block wins over the\n// hand-written record above, so re-running the research never loses data.\nconst RESEARCHED = {\n${lines.join("\n")}};\n${MARK_END}`;

let source = fs.readFileSync(DATA_FILE, "utf8");
const start = source.indexOf(MARK_START);
const end = source.indexOf(MARK_END);
if (start >= 0 && end > start) {
  source = source.slice(0, start) + block + source.slice(end + MARK_END.length);
} else {
  const anchor = "let n = 0;";
  source = source.replace(anchor, `${block}\n\n${anchor}`);
}
// mk() applies the researched values last.
source = source.replace(
  "    dataSource: extra.dataSource || \"curated\",\n  };\n}",
  "    dataSource: extra.dataSource || \"curated\",\n    ...(RESEARCHED[id] || {}),\n  };\n}",
);
fs.writeFileSync(DATA_FILE, source);
console.log(`\nWrote ${path.relative(ROOT, DATA_FILE)} with ${lines.filter((l) => l.includes(": {")).length} researched records.`);
